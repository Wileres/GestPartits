type Leaves<T, P extends string = ''> = T extends string
    ? P
    : T extends readonly string[]
      ? P
      : { [K in keyof T & string]: Leaves<T[K], P extends '' ? K : `${P}.${K}`> }[keyof T & string];

export type TranslationKey = Leaves<typeof ca>;

/**
 * Retorna el text de la clau i substitueix els marcadors {nom}.
 */
export function t(key: TranslationKey, params: Record<string, string | number> = {}): string {
    const value = key.split('.').reduce<unknown>((node, part) => (node as Record<string, unknown> | undefined)?.[part], ca);

    if (typeof value !== 'string') {
        throw new Error(`Falta la traducció: ${key}`);
    }

    return value.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

/** Últim accés i altres instants: «16/10/2026 01:15» (o «Mai»). */
export function formatDateTime(iso: string | null): string {
    if (iso === null) return t('users.never');

    const parts = new Intl.DateTimeFormat('en-GB', {
        timeZone: 'Europe/Madrid',
        day: '2-digit',
        month: '2-digit',
        year: 'numeric',
        hour: '2-digit',
        minute: '2-digit',
        hourCycle: 'h23',
    }).formatToParts(new Date(iso));
    const get = (type: Intl.DateTimeFormatPartTypes) => parts.find((p) => p.type === type)?.value ?? '';

    return `${get('day')}/${get('month')}/${get('year')} ${get('hour')}:${get('minute')}`;
}
